def load_language_pref():
    """讀取語言偏好：優先使用者資料目錄，其次打包內唯讀預設。"""
    candidates = [
        paths.get_user_data_path(LANGUAGE_FILE_NAME),
        paths.find_data_file(LANGUAGE_FILE_NAME),
        os.path.join(paths.project_root(), LANGUAGE_FILE_NAME),
    ]
    for p in candidates:
        if p and os.path.isfile(p):
            try:
                with open(p, "r", encoding="utf-8") as f:
                    data = json.load(f)
                lang = data.get("lang")
                if lang in (LANG_HANT, LANG_HANS):
                    return lang
            except Exception:
                continue
    return LANG_HANT


def save_language_pref(lang):
    """寫入語言偏好到使用者資料目錄。回傳 (ok, error_message)。"""
    path = paths.get_user_data_path(LANGUAGE_FILE_NAME)
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump({"lang": lang}, f, ensure_ascii=False, indent=2)
            f.write("\n")
        return True, ""
    except Exception as ex:
        return False, str(ex)


def set_language(lang):
    """設定介面語言並嘗試持久化。回傳 (ok, error_message)。"""
    global _current_lang
    if lang not in (LANG_HANT, LANG_HANS):
        return False, "invalid language"
    _current_lang = lang
    return save_language_pref(lang)
