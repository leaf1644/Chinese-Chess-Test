def get_lang():
    return _current_lang


def t(key, **kwargs):
    """依目前語言取字串；缺鍵時回退繁體。"""
    table = UI_STRINGS.get(_current_lang) or UI_STRINGS[LANG_HANT]
    text = table.get(key)
    if text is None:
        text = UI_STRINGS[LANG_HANT].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


